"""Regenerate compact GR equations from the ungauged reduced action (2.11).

Run from project/. The output is code, not a fitted reference solution.
"""
from pathlib import Path
import os

ROOT=Path(__file__).resolve().parents[1]
for key in ('TEMP','TMP'):
    (ROOT/'.cache/tmp').mkdir(parents=True,exist_ok=True)
    os.environ[key]=str(ROOT/'.cache/tmp')
import sympy as s


def derive():
    r=s.symbols('r',positive=True)
    b,f,g,h,w=[s.Function(k)(r) for k in ('b','f','g','h','w')]
    d=lambda v:s.diff(v,r)
    lag=g*s.sqrt(b*h/f)*(f*(d(g)**2/(2*g*g)+d(b)*d(g)/(b*g)
        +d(b)*d(h)/(2*b*h)+d(g)*d(h)/(g*h)+h*d(w)**2/(2*b))+8/g-2*h/g**2)
    equations=[]
    for v in (b,g,h,w):
        variation=s.diff(lag,v)-d(s.diff(lag,d(v)))
        equations.append(s.factor((variation/s.sqrt(b*h/f)).subs({d(d(g)):2,d(g):2*r,g:r*r})))
    unknown=[d(f),d(d(b)),d(d(h)),d(d(w))]
    solution=s.solve(equations,unknown,simplify=False)
    x=s.symbols('x');z=1-x;A=1-z*z
    B,F,H,W,P,Q,V=s.symbols('B F H W P Q V')
    values=[A*B,A*F,(1+z**4*H)/z**2,z**4*W]
    dx=lambda e:s.diff(e,x)+s.diff(e,B)*P+s.diff(e,H)*Q+s.diff(e,W)*V
    sub={r:1/z,b:values[0],f:values[1],h:values[2],w:values[3],
         d(b):z*z*dx(values[0]),d(h):z*z*dx(values[2]),d(w):z*z*dx(values[3])}
    fp,bpp,hpp,wpp=[s.factor(solution[v].subs(sub,simultaneous=True)) for v in unknown]
    rhs=[(bpp/z**4+2*dx(values[0])/z-dx(dx(values[0])))/A,
         (fp/z**2-s.diff(A,x)*F)/A,
         (hpp/z**4+2*dx(values[2])/z-dx(dx(values[2])))/z**2,
         (wpp/z**4+2*dx(values[3])/z-dx(dx(values[3])))/z**4]
    zz=s.symbols('z')
    rhs=[s.factor(e.subs(x,1-zz)) for e in rhs]
    replacements,reduced=s.cse(rhs,s.numbered_symbols('c'))
    lines=['"""Generated by experiments/derive_vacuum.py; do not edit by hand."""',
           '', 'def rhs(z, B, F, H, W, P, Q, V):',
           '    """Return Bxx,Fx,Hxx,Wxx; P=Bx,Q=Hx,V=Wx, z=1-x."""']
    lines += ['    '+str(v)+' = '+s.pycode(e) for v,e in replacements]
    lines += ['    return ('+', '.join(s.pycode(e) for e in reduced)+')','']
    (ROOT/'src/rotating_bh/_vacuum_generated.py').write_text('\n'.join(lines),encoding='utf-8')


if __name__=='__main__':
    derive()
