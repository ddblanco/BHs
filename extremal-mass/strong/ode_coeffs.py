"""Write the reduced fixed-J system as  A_i f' + B_i h'' + C_i = 0  (i = b, h)
and generate a python module with the six polynomial coefficients."""
import sys, pickle
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent/'code'))
import sympy as s
from reduced_system import r, alpha, f, h, p, q, t, C2
E = pickle.load(open(HERE/'reduced_ode.pkl', 'rb'))
lines = ['"""Generated by ode_coeffs.py: reduced fixed-J EGB system A f\' + B h\'\' + C = 0."""', '']
for name in ('eb', 'eh'):
    e = s.expand(E[name])
    P = s.Poly(e, p, t)
    A, B, C = P.coeff_monomial(p), P.coeff_monomial(t), P.coeff_monomial(1)
    assert s.expand(A*p+B*t+C-e) == 0
    for lab, X in (('A', A), ('B', B), ('C', C)):
        X = s.horner(s.expand(X.subs(C2, 32)), wrt=None) if False else s.expand(X.subs(C2, 32))
        lines.append(f'def {lab}_{name}(r, f, h, hp, alpha):')
        lines.append(f'    return {s.pycode(X)}')
        lines.append('')
(HERE/'_ode_generated.py').write_text('\n'.join(lines))
print('ok', len('\n'.join(lines)))
