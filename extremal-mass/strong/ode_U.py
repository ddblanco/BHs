"""Generate numerator/denominator of U = b'/b (lapse) as python functions (C2 = 32)."""
import sys, pickle
from pathlib import Path
import sympy as s
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent/'code'))
from reduced_system import r, alpha, f, h, q, C2
E = pickle.load(open(HERE/'reduced_ode.pkl', 'rb'))
U = E['U'].subs(C2, 32)
num, den = s.fraction(s.together(U))
src = ['"""Generated by ode_U.py: U = Unum/Uden = b\'/b."""', '',
       'def Unum(r, f, h, hp, alpha):', '    return '+s.pycode(s.expand(num)).replace('math.', ''), '',
       'def Uden(r, f, h, hp, alpha):', '    return '+s.pycode(den).replace('math.', ''), '']
(HERE/'_U_generated.py').write_text('\n'.join(src))
print('ok')
